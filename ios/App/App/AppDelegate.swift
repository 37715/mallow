    func application(_ application: UIApplication, didFinishLaunchingWithOptions launchOptions: [UIApplication.LaunchOptionsKey: Any]?) -> Bool {
        // **Without this the game is silent whenever the ringer switch is off.**
        //
        // WebAudio inside a WKWebView runs on the app's audio session, and the
        // default one obeys the hardware silent switch. Every purr, coin and
        // room tone is synthesised in `audio/audio.ts` and works perfectly —
        // and none of it reaches the speaker on a phone that is on silent,
        // which is most phones. Nothing errors, so it reads as "the audio is
        // broken" rather than "the audio is muted".
        //
        // `.playback` plays regardless of the switch. `.mixWithOthers` is the
        // polite half: the ambient bed is deliberately quiet enough to sit
        // under a podcast (§10), so it should not stop one.
        do {
            try AVAudioSession.sharedInstance().setCategory(.playback, options: [.mixWithOthers])
            try AVAudioSession.sharedInstance().setActive(true)
        } catch {
            // A café that is silent is still a café. Never fail to launch over this.
            print("[mallow] could not configure the audio session: \(error)")
        }
        return true
    }

